USE MAP_PROJECT;


-- 1. SKU TABLE
SELECT * FROM SKU;

-- 2. PL TABLE
SELECT * FROM PL;

-- 3. PRICE LIST TABLE
SELECT * FROM PRICE_LIST;

-- 4. SELLER MAPPING TABLE
SELECT * FROM SELLER_MAPPING;

-- 5. CATEGORY MAPPING TABLE
SELECT * FROM CATEGORY_MAPPING;

-- 6. PROMOTION TABLE
SELECT * FROM PROMOTION;

-- 7. RECORD COUNT OF ALL TABLES
SELECT 'SKU' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM SKU
UNION ALL
SELECT 'PL', COUNT(*)
FROM PL
UNION ALL
SELECT 'PRICE_LIST', COUNT(*)
FROM PRICE_LIST
UNION ALL
SELECT 'SELLER_MAPPING', COUNT(*)
FROM SELLER_MAPPING
UNION ALL
SELECT 'CATEGORY_MAPPING', COUNT(*)
FROM CATEGORY_MAPPING
UNION ALL
SELECT 'PROMOTION', COUNT(*)
FROM PROMOTION;